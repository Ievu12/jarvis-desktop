@dataclass(frozen=True)
class TextCue:
    """One on-screen text overlay within a scene - exact text,
    position, timing window (relative to the scene's OWN start, i.e. 0
    means "right when this scene begins"), and animation style. A scene
    may have zero, one, or several cues -
    jarvis.reel_generator.scene_render renders each cue as its own text
    layer at its own moment, rather than a single static caption for
    the whole scene."""

    text: str
    position: str  # one of TEXT_POSITION_CHOICES
    start_seconds: float  # relative to the scene's own start
    end_seconds: float  # relative to the scene's own start
    animation: str  # one of TEXT_ANIMATION_CHOICES

    @property
    def duration_seconds(self) -> float:
        return round(self.end_seconds - self.start_seconds, 1)


@dataclass(frozen=True)
class ScenePlan:
    """The full per-scene visual plan, one per
    jarvis.reel_generator.storyboard.Scene, matched by `scene_number`.

    `visual_type` (jarvis.story_generator's original, narrower
    VISUAL_TYPE_CHOICES) is the field that package's own prompt/
    construction has always populated; `visual_source` (AI Reel
    Generator's own newer, broader requirement-1 vocabulary,
    VISUAL_SOURCE_CHOICES) defaults to DEFAULT_VISUAL_SOURCE so
    jarvis.story_generator's existing ScenePlan(...) construction (which
    has never passed it) keeps working unmodified - see
    jarvis.reel_generator.storyboard's own scene generation for the
    call site that DOES populate it explicitly. `transition` similarly
    defaults to DEFAULT_TRANSITION ("cut") for the same reason -
    jarvis.story_generator's own per-scene `transition` concept already
    lives on jarvis.reel_generator.storyboard.Scene itself (a DIFFERENT
    field, on a different dataclass - see that dataclass's own
    docstring), so this ScenePlan-level transition is new, AI Reel
    Generator-only vocabulary that Story Generator's own prompt has
    never populated.

    `voiceover`/`camera_shot`/`camera_movement`/`environment`/
    `subject_action`/`b_roll_type`/`text_animation`/`music_mood` are
    the Visual Story Director brief's own additional per-scene fields -
    all default to "" (or the matching *_CHOICES table's own DEFAULT_*
    constant) so existing ScenePlan(...) construction (jarvis
    .story_generator's own, and any already-saved project's stored
    data) keeps working unmodified. `generated_visual_path`/
    `generated_video_path` record where jarvis.reel_generator
    .image_generation's own real, saved output lives for this scene (a
    per-project file path, set by jarvis.reel_generator.scene_render
    once it actually generates/saves an image for this scene - see that
    module's own docstring) - None means no real generated visual exists
    for this scene yet (either generation hasn't run, isn't configured,
    or failed), in which case rendering falls back to this codebase's
    own Pillow treatment."""

    scene_number: int
    visual_type: str  # one of VISUAL_TYPE_CHOICES
    main_visual_prompt: str  # detailed description for the main visual
    supporting_visuals: tuple[str, ...]  # short labels, e.g. "arrow", "before/after split"
    text_cues: tuple[TextCue, ...]
    sticker: str  # one of STICKER_NAME_CHOICES - "none" means no sticker this scene
    sticker_start_seconds: float  # relative to the scene's own start - when the sticker appears
    motion: str  # one of MOTION_CHOICES
    emotion: str  # one or two words, e.g. "hopeful", "anxious"
    pacing: str  # one of PACING_CHOICES
    lighting: str  # one of LIGHTING_CHOICES
    visual_source: str = DEFAULT_VISUAL_SOURCE  # one of VISUAL_SOURCE_CHOICES (AI Reel Generator's requirement 1)
    transition: str = DEFAULT_TRANSITION  # one of TRANSITION_CHOICES - transition INTO the next scene
    is_hook: bool = False  # requirement 6: the first 1-3 seconds get special hook treatment
    voiceover: str = ""  # the spoken narration line for this scene (stored, not yet synthesized - see this dataclass's own docstring)
    camera_shot: str = DEFAULT_CAMERA_SHOT  # one of CAMERA_SHOT_CHOICES - descriptive, shown in the storyboard UI
    camera_movement: str = DEFAULT_CAMERA_MOVEMENT  # one of CAMERA_MOVEMENT_CHOICES - descriptive
    environment: str = ""  # short description of the setting/location, e.g. "cozy bedroom, morning light"
    subject_action: str = ""  # short description of what the subject is doing, e.g. "wrapped in a blanket, sipping tea"
    b_roll_type: str = DEFAULT_B_ROLL_TYPE  # one of B_ROLL_TYPE_CHOICES
    text_animation: str = ""  # free-text animation note for on_screen_text (distinct from a TextCue's own per-cue `animation`)
    music_mood: str = DEFAULT_MUSIC_MOOD  # one of MUSIC_MOOD_CHOICES - descriptive only, no music mixing exists yet
    generated_visual_path: str | None = None  # path to a real jarvis.reel_generator.image_generation-produced image for this scene, if one was generated and saved
    generated_video_path: str | None = None  # reserved for a future real video-clip generation capability - always None today (no such capability exists)
    visual_quality_score: int = 10  # 1-10, see jarvis.reel_generator.visual_quality's own docstring - defaults to 10 (best) so every EXISTING ScenePlan(...) construction (a project saved before this field existed) is treated as already having passed the quality bar, never retroactively flagged

    @property
    def sticker_glyph(self) -> str:
        """The actual emoji character to composite, or "" if this scene
        has no sticker - see STICKER_CHOICES for the name->glyph table."""
        return STICKER_CHOICES.get(self.sticker, "")


@dataclass(frozen=True)
class VisualPlan:
    """A Reel's or Story's complete set of per-scene plans - the
    artifact that gets "passed to the existing scene visual generation
    pipeline so that the actual generated video contains these visual
    elements" (jarvis.reel_generator.scene_render consumes this
    directly, one ScenePlan per Scene). `visual_style`, if set, is the
    whole-Reel style selector (requirement 8, VISUAL_STYLE_CHOICES) -
    empty string for a jarvis.story_generator project, which has no
    equivalent whole-story style selector of its own."""

    scenes: tuple[ScenePlan, ...]
    visual_style: str = ""

    def for_scene(self, scene_number: int) -> ScenePlan | None:
        return next((p for p in self.scenes if p.scene_number == scene_number), None)


def set_scene_generated_video(plan: VisualPlan, scene_number: int, video_path: str | None, *, clear_error: bool = True) -> VisualPlan:
    """NATURAL MOTION / HYBRID mode's own ONE write path for
    `ScenePlan.generated_video_path` (previously always None - see that
    field's own docstring) - called by jarvis.reel_generator.motion_engine
    once it has a real, saved video clip path for this scene (or wants to
    clear a stale one, by passing `video_path=None`). Mutates ONLY the
    one matching scene's own `generated_video_path`, leaving every other
    scene in `plan` - and every other field on the matching scene itself
    - completely untouched, same `dataclasses.replace()`-on-one-scene
    pattern jarvis.reel_generator.storyboard's own regenerate_scene_*()
    helpers already use for single-aspect edits.

    `clear_error` is currently unused by this function itself (there is
    no error field on ScenePlan to clear - a generation failure's error
    message lives on the separate jarvis.reel_generator.scenes
    .SceneMotionClip returned by motion_engine, never mutated into the
    ScenePlan itself) - kept as an explicit, forward-declared parameter
    so a future ScenePlan-level error field (should one ever be added)
    has an obvious, already-documented place to be wired in without
    changing this function's call sites.

    Returns the SAME plan unchanged (a new object, but structurally
    identical) if `scene_number` doesn't match any scene in `plan` -
    never raises for an unknown scene number, matching this codebase's
    general "a caller-supplied scene number that doesn't exist is a
    silent no-op, not an exception" convention for per-scene mutators."""
    updated_scenes = tuple(
        dataclasses.replace(p, generated_video_path=video_path) if p.scene_number == scene_number else p
        for p in plan.scenes
    )
    return dataclasses.replace(plan, scenes=updated_scenes)
