"""Per-scene visual plan - shared by AI Reel Generator (this feature's
own "Smart Visual Director" brief) and jarvis.story_generator (that
feature's own earlier visual-richness brief, requirements 1-7): the
structured description of HOW a scene should actually look and move,
beyond its plain on_screen_text/visual_description
(jarvis.reel_generator.storyboard.Scene's own fields, unchanged) -
visual type/source, supporting visual elements, on-screen text cue
timing/position/animation, an optional sticker/emoji, motion, and
emotional direction (pacing/lighting).

Originally written for jarvis.story_generator (see that package's own
history), PROMOTED here once AI Reel Generator's own Smart Visual
Director brief needed the exact same shape - rather than duplicate
ScenePlan/TextCue/VisualPlan and their Pillow-compositing rendering
code a second time, both features import this one shared module and
each writes its own LLM prompt against it (jarvis.reel_generator
.storyboard's own scene generation, jarvis.story_generator.story_scenes'
own). jarvis.story_generator now imports ScenePlan/TextCue/VisualPlan
FROM here rather than defining its own copy - see that package's own
modules for the re-export.

Generated by the SAME LLM call that produces each feature's own Scene
list (no second round-trip), one ScenePlan per Scene, matched by scene
number. Stored as its own JSON blob, separate from a project's
storyboard data, so a project saved before this plan existed (or one
whose plan failed to parse) degrades gracefully to a plain scene render
- jarvis.reel_generator.scenes.render_all_scenes() and
jarvis.reel_generator.scene_render.render_all_story_scenes() both
already work from Scene alone; a ScenePlan only ever ADDS detail on top
of what a Scene already provides, never replaces it.

Rendering (turning a ScenePlan into actual pixels/motion in the
exported video) is a SEPARATE stage - jarvis.reel_generator.scene_render
(main visual/supporting visuals/text cues/stickers all composited via
Pillow) and an optional motion_by_scene passed to
jarvis.reel_generator.export.export_reel_video() (Ken Burns pan/zoom via
ffmpeg's zoompan filter) - this module only defines and validates the
PLAN's shape; see either of those modules' own docstrings for why they
are kept separate from planning."""

